// generator: md.mdp  (production — unchanged from v0.2)
function generateMD(ctx){
  const prodS  = Math.round(ctx.prod  * 1e6 / (ctx.dt * 1000));
  const equilS = Math.round(ctx.equil * 1e6 / (ctx.dt * 1000));
  const L = buildLines((c,s,b,kv) => {
    c('; md.mdp -- production run -- generated by mdp-gen');
    c('; System: '+ctx.system+'  |  Force field: '+ctx.ff+'  |  Water: '+ctx.water);
    b(); s('; Run control');
    kv('integrator','md'); kv('nsteps',prodS,ctx.prod+' ns'); kv('dt',ctx.dt,ctx.dt*1000+' fs timestep');
    b(); s('; Output control');
    kv('nstxout-compressed','5000','trajectory every 10 ps');
    kv('nstvout','0'); kv('nstfout','0'); kv('nstlog','5000'); kv('nstenergy','5000');
    b(); s('; Neighbor searching');
    kv('cutoff-scheme','Verlet'); kv('ns_type','grid'); kv('nstlist','10');
    if(ctx.rcoul) kv('rlist', ctx.rcoul);
    b(); s('; Electrostatics');
    kv('coulombtype', ctx.coulomb);
    if(ctx.rcoul) kv('rcoulomb', ctx.rcoul);
    if(ctx.coulomb==='PME'){ kv('pme_order','4'); kv('fourierspacing','0.16'); }
    if(ctx.coulomb==='Reaction-Field') kv('epsilon-rf','0','tin-foil BC');
    b(); s('; van der Waals');
    kv('vdwtype','Cut-off');
    if(ctx.rvdw) kv('rvdw', ctx.rvdw);
    kv('DispCorr', ctx.dispCorr);
    b(); s('; Temperature coupling');
    kv('tcoupl', ctx.tcoupl);
    if(ctx.useTc){ kv('tc-grps','System'); kv('tau_t',ctx.taut); kv('ref_t',ctx.temp); }
    b(); s('; Pressure coupling');
    kv('pcoupl', ctx.pcoupl);
    if(ctx.usePc){ kv('pcoupltype','isotropic'); kv('tau_p',ctx.taup); kv('ref_p',ctx.pres); kv('compressibility',ctx.compress); }
    b(); s('; Periodic boundary conditions');
    kv('pbc', ctx.pbc);
    b(); s('; Constraints');
    kv('constraints',ctx.cons); kv('constraint_algorithm','LINCS'); kv('lincs_iter','1'); kv('lincs_order','4');
    b();
    c('; Equilibration run: use nsteps = '+equilS+' ('+ctx.equil+' ns)');
    c('; Energy minimization: use nsteps = '+ctx.em);
    c('; Water model: '+ctx.water);
  });
  return L;
}

// tab switching
function switchTab(tab){
  activeTab = tab;
  document.querySelectorAll('.tab-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.tab === tab);
  });
  document.querySelectorAll('.tab-pane').forEach(pane => {
    pane.classList.toggle('active', pane.id === 'pane-'+tab);
  });
}

// main generate — runs all 5 and populates all panes
function generate(){
  const ctx = getCtx();
  const generators = {
    ions: generateIons,
    em:   generateEM,
    nvt:  generateNVT,
    npt:  generateNPT,
    md:   generateMD,
  };
  for(const [name, fn] of Object.entries(generators)){
    const lines = fn(ctx);
    const pane  = document.getElementById('pane-'+name);
    if(pane) pane.querySelector('.output-code').innerHTML = renderLines(lines);
    // stash plain text for copy/download
    pane._lines = lines;
  }
  // make sure active tab is visible
  switchTab(activeTab);
}

// copy & download
function copyActive(){
  const pane = document.getElementById('pane-'+activeTab);
  const txt  = pane ? pane.querySelector('.output-code').innerText : '';
  navigator.clipboard.writeText(txt).then(() => {
    const btn = document.getElementById('copybtn');
    btn.textContent = 'copied!'; btn.classList.add('copied');
    setTimeout(() => { btn.textContent = 'copy'; btn.classList.remove('copied'); }, 2000);
  });
}

function downloadActive(){
  const pane = document.getElementById('pane-'+activeTab);
  if(!pane) return;
  const txt  = pane.querySelector('.output-code').innerText;
  const blob = new Blob([txt], {type:'text/plain'});
  const url  = URL.createObjectURL(blob);
  const a    = document.createElement('a');
  a.href     = url;
  a.download = activeTab + '.mdp';
  a.click();
  URL.revokeObjectURL(url);
}

