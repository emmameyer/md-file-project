// generator: nvt.mdp
function generateNVT(ctx){
  const p = (ctx.ffData.nvt) || {};
  const isStub = !ctx.ffData.nvt;
  const equilS = Math.round(ctx.equil * 1e6 / (ctx.dt * 1000));
  const L = buildLines((c,s,b,kv) => {
    c('; nvt.mdp -- generated by mdp-gen');
    c('; System: '+ctx.system+'  |  Force field: '+ctx.ff+'  |  Water: '+ctx.water);
    if(isStub){ c('; NOTE: placeholder values -- fill in parameters.js for this force field'); }
    b(); s('; Run control');
    kv('integrator', p.integrator||'md');
    kv('nsteps',     p.nsteps||equilS,  ctx.equil+' ns equilibration (NVT)');
    kv('dt',         p.dt||ctx.dt,      (p.dt||ctx.dt)*1000+' fs timestep');
    b(); s('; Output');
    kv('nstxout-compressed','5000'); kv('nstvout','0'); kv('nstfout','0'); kv('nstlog','5000'); kv('nstenergy','5000');
    b(); s('; Neighbor searching');
    kv('cutoff-scheme','Verlet'); kv('ns_type','grid'); kv('nstlist','10');
    if(p.rcoulomb) kv('rlist', p.rcoulomb);
    b(); s('; Electrostatics');
    kv('coulombtype', p.coulombtype||ctx.coulomb);
    if(p.rcoulomb) kv('rcoulomb', p.rcoulomb);
    if((p.coulombtype||ctx.coulomb)==='PME'){ kv('pme_order','4'); kv('fourierspacing','0.16'); }
    b(); s('; van der Waals');
    kv('vdwtype','Cut-off');
    if(p.rvdw) kv('rvdw', p.rvdw);
    kv('DispCorr', p.dispCorr||ctx.dispCorr);
    b(); s('; Temperature coupling — NVT');
    kv('tcoupl',   p.tcoupl||ctx.tcoupl);
    kv('tc-grps',  'System');
    kv('tau_t',    ctx.taut);
    kv('ref_t',    ctx.temp);
    b(); s('; No pressure coupling in NVT');
    kv('pcoupl','no');
    b(); s('; Periodic boundary conditions');
    kv('pbc', ctx.pbc);
    b(); s('; Constraints');
    kv('constraints',         p.constraints||ctx.cons);
    kv('constraint_algorithm','LINCS');
    kv('lincs_iter',          '1');
    kv('lincs_order',         '4');
    b(); s('; Generate velocities');
    kv('gen_vel',  'yes');
    kv('gen_temp', ctx.temp);
    kv('gen_seed', '-1');
  });
  return L;
}

